public class Numbers {
    public static void main(String[] args) {
        // scientific numbers:
        float num1 = 4e5f;
        double num2 = 5E6d;
        double light_speed = 3E8d;
        System.out.println(num1);
        System.out.println(num2);
        System.out.println(light_speed);
    }
}
